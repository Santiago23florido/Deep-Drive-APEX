"""Export the dataset tracks as Gazebo worlds of ``rc_sim_description``.

Each track becomes ``rc_sim_description/worlds/pose_dataset/<track>.world``
with the same geometry the dataset used (collisions and visuals), the Gazebo
systems the ROS simulation needs (physics, user commands, scene broadcaster,
IMU and rendering sensors for the car's GPU LiDAR and camera) and a
real-time factor of 1. A scenario ``pose_<track>`` is added to
``config/apex_sim_scenarios.json`` with the spawn pose at the start of the
track's reference path, so the tracks work with the usual launchers:

    ./simulation/tools/sim/apex_sim_up.sh --scenario pose_oval_asym --rviz
    ros2 launch rc_sim_description apex_sim.launch.py scenario:=pose_urban_grid

or directly: ``gz sim worlds/pose_dataset/oval_asym.world`` (track only).
"""

from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any
import xml.etree.ElementTree as ET

from .geometry import world_sdf, write_xml
from .tracks import Track, load_track, load_track_specs
from .vehicle import SIM_ROOT

RC_SIM = SIM_ROOT / "ros2_ws" / "src" / "rc_sim_description"
WORLD_DIR = RC_SIM / "worlds" / "pose_dataset"
SCENARIOS = RC_SIM / "config" / "apex_sim_scenarios.json"


def spawn_pose(track: Track, rear_axle_offset: float = -0.15) -> dict[str, float]:
    """base_link pose that puts the rear axle on the start of the reference path."""
    ref = track.reference
    heading = float(ref.heading[0])
    x = float(ref.xy[0, 0]) - rear_axle_offset * math.cos(heading)
    y = float(ref.xy[0, 1]) - rear_axle_offset * math.sin(heading)
    return {"x": round(x, 4), "y": round(y, 4), "z": 0.02, "yaw_deg": round(math.degrees(heading), 3)}


def gazebo_world(track: Track) -> ET.Element:
    root = world_sdf(track.geometry, ground_mu=track.ground_mu, real_time_factor=1.0)
    world = root.find("world")
    imu = ET.Element("plugin", {"filename": "gz-sim-imu-system", "name": "gz::sim::systems::Imu"})
    sensors = ET.Element("plugin", {"filename": "gz-sim-sensors-system", "name": "gz::sim::systems::Sensors"})
    ET.SubElement(sensors, "render_engine").text = "ogre2"
    # Keep the plugins before the models, as in the hand-written worlds.
    index = max(i for i, el in enumerate(list(world)) if el.tag == "plugin") + 1
    world.insert(index, imu)
    world.insert(index + 1, sensors)
    gui = ET.SubElement(world, "gui", {"fullscreen": "0"})
    cam = ET.SubElement(gui, "camera", {"name": "user_camera"})
    cx, cy = track.centerline.xy.mean(axis=0)
    ET.SubElement(cam, "pose").text = f"{cx:.2f} {cy - 14.0:.2f} 14.0 0 0.75 1.5708"
    return root


def export_gazebo_worlds(tracks: list[str] | None = None, world_dir: Path = WORLD_DIR, scenarios_path: Path = SCENARIOS) -> dict[str, Any]:
    specs = load_track_specs()
    names = tracks or list(specs)
    world_dir.mkdir(parents=True, exist_ok=True)
    index: dict[str, Any] = {}
    for name in names:
        track = load_track(name)
        root = gazebo_world(track)
        header = ET.Comment(
            f" Generated by simulation/tools/generate_pose_dataset.py --install-gazebo-worlds from tools/pose_dataset/config/tracks.yaml ({name}). "
            "Do not edit by hand: change the YAML and regenerate. "
        )
        root.insert(0, header)
        write_xml(root, world_dir / f"{name}.world")
        index[name] = {
            "world": f"pose_dataset/{name}.world",
            "scenario": f"pose_{name}",
            "role": specs[name].get("role", ""),
            "held_out_zero_shot": bool(specs[name].get("held_out", False)),
            "family": track.family,
            "description": " ".join(track.description.split()),
            "spawn": spawn_pose(track),
            "reference_length_m": track.meta["reference_length_m"],
            "min_reference_radius_m": track.meta["min_reference_radius_m"],
            "width_m": [track.meta["width_min_m"], track.meta["width_max_m"]],
        }
    index_path = world_dir / "tracks_index.json"
    if index_path.exists():  # exporting a subset keeps the other tracks
        merged = json.loads(index_path.read_text(encoding="utf-8"))
        merged.update(index)
        index = {k: merged[k] for k in list(specs) if k in merged}
    index_path.write_text(json.dumps(index, indent=2) + "\n", encoding="utf-8")

    _append_scenarios(scenarios_path, index)
    return index


def _append_scenarios(path: Path, index: dict[str, Any]) -> None:
    """Add ``pose_*`` scenarios at the end of the ``scenarios`` object.

    The existing text of the file is kept byte for byte: previously generated
    ``pose_*`` entries (always the last ones) are replaced, nothing else is
    re-serialised.
    """
    text = path.read_text(encoding="utf-8")
    start = text.index('"scenarios"')
    open_brace = text.index("{", start)
    depth = 0
    for pos in range(open_brace, len(text)):
        if text[pos] == "{":
            depth += 1
        elif text[pos] == "}":
            depth -= 1
            if depth == 0:
                close = pos
                break
    body = text[open_brace + 1 : close]
    marker = body.find(',\n    "pose_')
    if marker >= 0:
        body = body[:marker]
    body = body.rstrip()
    entries = []
    for info in index.values():
        entry = json.dumps({"world": info["world"], "spawn": info["spawn"]}, indent=2)
        entry = entry.replace("\n", "\n    ")
        entries.append(f'    "{info["scenario"]}": {entry}')
    new_body = body + ",\n" + ",\n".join(entries) + "\n  "
    new_text = text[: open_brace + 1] + new_body + text[close:]
    json.loads(new_text)  # must stay valid JSON
    path.write_text(new_text, encoding="utf-8")
